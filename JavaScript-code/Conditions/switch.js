/* 
Many conditions
one variable
many outputs
to simplify if-else
    
*/

let day = 3;
switch(day){
    case 1:
        console.log("Monday");
        break;
    case 2:
        console.log("Tuesday");
        break;
    case 3:
        console.log("Wensday");
        break;
    case 4:
        console.log("Thursday");
        break;
    case 5:
        console.log("Friday");
        break;
    case 6:
        console.log("Satuarday");
        break;
    case 7:
        console.log("Sunday");
        break;
    default:
        console.log("Invalid day");    
}